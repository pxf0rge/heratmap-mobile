-- ============================================================================
-- HeratMap — فاز ۱: اسکیمای پایه، اصلاح وضعیت فعلی، RLS، ایندکس‌ها، باکت تصاویر
-- این فایل «idempotent» است: اجرای دوباره‌ی آن نه خطا می‌دهد و نه داده را پاک می‌کند.
--   اعمال: Supabase Dashboard → SQL Editor → paste → Run
--   یا:    supabase db push   (نیازمند supabase login + link)
-- ============================================================================

begin;

-- ── افزونه‌ی جستجوی متنی (برای ilike سریع روی نام/آدرس/دسته) ────────────────
create extension if not exists pg_trgm;

-- ── جدول فازها ──────────────────────────────────────────────────────────────
create table if not exists public.phases (
  id      bigint generated by default as identity primary key,
  name    text    not null,
  number  integer not null default 0,
  image   text
);

-- جدول‌های موجود ممکن است created_at نداشته باشند
alter table public.phases
  add column if not exists created_at timestamptz not null default now();

comment on table  public.phases       is 'فازهای شهرک صنعتی هرات';
comment on column public.phases.name  is 'نام فاز؛ همان مقداری که در factories.phase ذخیره می‌شود (مثال: فاز 1)';
comment on column public.phases.image is 'آدرس کامل تصویر در باکت images (می‌تواند تهی باشد)';

-- نام فاز باید یکتا باشد (factories.phase به همین ستون ارجاع می‌دهد)
create unique index if not exists phases_name_key on public.phases (name);
create index if not exists phases_number_idx on public.phases (number);

-- ── جدول شرکت‌ها / کارخانه‌ها ───────────────────────────────────────────────
create table if not exists public.factories (
  id            bigint generated by default as identity primary key,
  name          text not null,
  category      text not null default '',
  phase         text not null default '',
  lat           double precision,
  lon           double precision,
  address       text not null default '',
  phone         text not null default '',
  working_hours text not null default '',
  description   text not null default '',
  image         text not null default ''
);

alter table public.factories
  add column if not exists created_at timestamptz not null default now();

comment on table  public.factories       is 'شرکت‌ها و کارخانه‌های شهرک صنعتی هرات';
comment on column public.factories.phase is 'نام فاز؛ باید با یکی از مقادیر phases.name مو‌به‌مو یکسان باشد';
comment on column public.factories.image is 'چند آدرس تصویر که با کاراکتر | جدا شده‌اند';
comment on column public.factories.working_hours is 'ساعت کاری متنی، مثال: 7 - 7';
comment on column public.factories.lat   is 'عرض جغرافیایی WGS84؛ صفر یعنی مختصات نامعتبر';

-- ============================================================================
-- اصلاح وضعیت فعلی دیتابیس زنده (باگ‌های شناخته‌شده)
-- ============================================================================

-- [!] جدول زنده یک کلید خارجی اشتباه دارد: factories.id → phases.id
--     نتیجه: افزودن هر شرکت جدید خطای 23503 می‌دهد و عملاً فقط به تعداد فازها
--     می‌توان شرکت داشت. این محدودیت باید حذف شود.
alter table public.factories drop constraint if exists factories_id_fkey;

-- ستون‌های متنی باید مقدار پیش‌فرض داشته باشند تا درج ردیف با فیلدهای خالی
-- خطای NOT NULL ندهد.
alter table public.factories
  alter column category      set default '',
  alter column phase         set default '',
  alter column address       set default '',
  alter column phone         set default '',
  alter column working_hours set default '',
  alter column description   set default '',
  alter column image         set default '';
alter table public.factories
  alter column category      drop not null,
  alter column phase         drop not null,
  alter column address       drop not null,
  alter column phone         drop not null,
  alter column working_hours drop not null,
  alter column description   drop not null,
  alter column image         drop not null;

-- مختصات می‌تواند نامعلوم باشد (اپ مقدار صفر/تهی را «نامعتبر» می‌داند)
alter table public.factories
  alter column lat drop not null,
  alter column lon drop not null;

-- محدوده‌ی معتبر مختصات (NOT VALID: ردیف‌های قدیمی را رد نمی‌کند، ردیف‌های جدید را چک می‌کند)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'factories_lat_range') then
    alter table public.factories
      add constraint factories_lat_range check (lat is null or (lat >= -90 and lat <= 90)) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'factories_lon_range') then
    alter table public.factories
      add constraint factories_lon_range check (lon is null or (lon >= -180 and lon <= 180)) not valid;
  end if;
end $$;

-- کلید خارجی درست: factories.phase → phases.name
-- (NOT VALID تا داده‌ی قدیمی مشکلی نسازد؛ برای ردیف‌های جدید اعمال می‌شود)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'factories_phase_fkey') then
    alter table public.factories
      add constraint factories_phase_fkey
      foreign key (phase) references public.phases (name)
      on update cascade on delete restrict
      not valid;
  end if;
end $$;

-- ── ایندکس‌های جستجو ───────────────────────────────────────────────────────
create index if not exists factories_phase_idx on public.factories (phase);
create index if not exists factories_name_trgm_idx on public.factories using gin (name gin_trgm_ops);
create index if not exists factories_addr_trgm_idx on public.factories using gin (address gin_trgm_ops);
create index if not exists factories_cat_trgm_idx  on public.factories using gin (category gin_trgm_ops);

-- ── دسترسی‌ها (GRANT) ───────────────────────────────────────────────────────
grant select on public.factories to anon, authenticated;
grant select on public.phases    to anon, authenticated;

-- ── RLS: خواندن عمومی، نوشتن فقط با service_role ────────────────────────────
-- نکته: کلید عمومی (anon/publishable) هیچ‌گاه نباید بنویسد.
alter table public.factories enable row level security;
alter table public.phases    enable row level security;

drop policy if exists factories_public_read on public.factories;
create policy factories_public_read on public.factories
  for select to anon, authenticated using (true);

drop policy if exists phases_public_read on public.phases;
create policy phases_public_read on public.phases
  for select to anon, authenticated using (true);

-- ── باکت تصاویر: عمومی برای خواندن، بدون اجازه‌ی نوشتن از سمت کلاینت ────────
insert into storage.buckets (id, name, public)
values ('images', 'images', true)
on conflict (id) do update set public = true;

drop policy if exists images_public_read on storage.objects;
create policy images_public_read on storage.objects
  for select to anon, authenticated using (bucket_id = 'images');

drop policy if exists images_no_client_write on storage.objects;
create policy images_no_client_write on storage.objects
  for insert to anon, authenticated with check (false);

commit;
