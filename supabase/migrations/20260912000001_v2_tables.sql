-- ============================================================================
-- HeratMap V2 — جدول‌های اخبار، اطلاعیه‌ها و شماره‌های ضروری
-- اجرای مجدد بی‌خطر است (idempotent).
-- ============================================================================

begin;

-- ── جدول اخبار ───────────────────────────────────────────────────────────────
create table if not exists public.news (
  id            bigint generated by default as identity primary key,
  title         text    not null default '',
  summary       text    not null default '',
  body          text    not null default '',
  image         text    not null default '',
  cover_image   text    not null default '',
  published_at  timestamptz,
  created_at    timestamptz not null default now(),
  is_active     boolean not null default true
);

comment on table  public.news   is 'اخبار شهرک صنعتی هرات';
comment on column public.news.title         is 'عنوان خبر';
comment on column public.news.summary       is 'خلاصهٔ خبر (نمایش در کارت)';
comment on column public.news.body          is 'متن کامل خبر';
comment on column public.news.image         is 'تصویر داخل متن (اختیاری)';
comment on column public.news.cover_image   is 'تصویر شاخص کارت خبر';
comment on column public.news.published_at  is 'تاریخ انتشار؛ NULL = هنوز منتشر نشده';
comment on column public.news.is_active     is 'آیا خبر فعال و نمایش داده شود؟';

create index if not exists news_published_at_idx on public.news (published_at desc);
create index if not exists news_is_active_idx on public.news (is_active);

-- ── جدول اطلاعیه‌ها ──────────────────────────────────────────────────────────
create table if not exists public.announcements (
  id            bigint generated by default as identity primary key,
  title         text    not null default '',
  body          text    not null default '',
  image         text    not null default '',
  published_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz not null default now(),
  is_active     boolean not null default true
);

comment on table  public.announcements  is 'اطلاعیه‌های شهرک صنعتی هرات';
comment on column public.announcements.title    is 'عنوان اطلاعیه';
comment on column public.announcements.body     is 'متن اطلاعیه';
comment on column public.announcements.image    is 'تصویر اطلاعیه (اختیاری)';
comment on column public.announcements.expires_at is 'تاریخ انقضا؛ بعد از آن نمایش داده نمی‌شود';

create index if not exists announcements_published_at_idx
  on public.announcements (published_at desc);
create index if not exists announcements_is_active_idx
  on public.announcements (is_active);

-- ── جدول شماره‌های ضروری ─────────────────────────────────────────────────────
create table if not exists public.emergency_contacts (
  id            bigint generated by default as identity primary key,
  name          text    not null default '',
  phone         text    not null default '',
  icon          text    not null default '',
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now(),
  is_active     boolean not null default true
);

comment on table  public.emergency_contacts is 'شماره‌های ضروری شهرک صنعتی هرات';
comment on column public.emergency_contacts.name  is 'نام سرویس (پلیس، آمبولانس، ...)';
comment on column public.emergency_contacts.phone is 'شماره تماس';
comment on column public.emergency_contacts.icon  is 'نام آیکن Material (بدون پیشوند)';
comment on column public.emergency_contacts.sort_order is 'ترتیب نمایش';

create index if not exists emergency_contacts_sort_idx
  on public.emergency_contacts (sort_order);
create index if not exists emergency_contacts_is_active_idx
  on public.emergency_contacts (is_active);

-- ── دسترسی‌ها (GRANT) ─────────────────────────────────────────────────────────
grant select on public.news         to anon, authenticated;
grant select on public.announcements to anon, authenticated;
grant select on public.emergency_contacts to anon, authenticated;

-- ── RLS ──────────────────────────────────────────────────────────────────────
alter table public.news              enable row level security;
alter table public.announcements     enable row level security;
alter table public.emergency_contacts enable row level security;

drop policy if exists news_public_read   on public.news;
create policy news_public_read   on public.news
  for select to anon, authenticated
  using (is_active = true);

drop policy if exists news_admin_write on public.news;
create policy news_admin_write on public.news
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists announcements_public_read
  on public.announcements;
create policy announcements_public_read
  on public.announcements
  for select to anon, authenticated
  using (is_active = true);

drop policy if exists announcements_admin_write
  on public.announcements;
create policy announcements_admin_write
  on public.announcements
  for all to authenticated
  using (true)
  with check (true);

drop policy if exists emergency_contacts_public_read
  on public.emergency_contacts;
create policy emergency_contacts_public_read
  on public.emergency_contacts
  for select to anon, authenticated
  using (is_active = true);

drop policy if exists emergency_contacts_admin_write
  on public.emergency_contacts;
create policy emergency_contacts_admin_write
  on public.emergency_contacts
  for all to authenticated
  using (true)
  with check (true);

-- ── باکت اخبار و اطلاعیه‌ها ──────────────────────────────────────────────────
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do update set public = true;

drop policy if exists media_public_read on storage.objects;
create policy media_public_read
  on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'media');

drop policy if exists media_no_client_write on storage.objects;
create policy media_no_client_write
  on storage.objects
  for insert to anon, authenticated
  with check (false);

commit;
